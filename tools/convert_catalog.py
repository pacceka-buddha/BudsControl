#!/usr/bin/env python3
"""Converts the upstream Swift device catalog into Rust.

    python tools/convert_catalog.py [path/to/DeviceCatalog.swift] > crates/buds-core/src/catalog/generated.rs

Default input: reference/upstream/Sources/DeviceCatalog.swift (a clone of the upstream repository).
Upstream generates that file from RawS-Music's HeyMelody profiles (Apache-2.0) and the Noctalia
oppo-pods plugin (MIT); see THIRD_PARTY_NOTICES.md. Do not edit the output by hand; re-run this.

The Swift entries look like:

    "065414": DeviceModel(name: "OnePlus Buds 4", brand: .oneplus,
                         modeTypes: [1, 2, 3],
                         setBits: [0: 1, 1: 5],
                         reportedBits: [0: 1, 1: 5],
                         eqPresets: [(0, 11), (1, 14)],
                         features: [.customEQ, .equalizer])      # or `features: nil`
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src_path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "reference/upstream/Sources/DeviceCatalog.swift"
src = src_path.read_text(encoding="utf-8")

FEATURES = {
    "noiseControl": "NoiseControl",
    "equalizer": "Equalizer",
    "customEQ": "CustomEq",
    "lowLatency": "LowLatency",
    "findBuds": "FindBuds",
    "gestures": "Gestures",
}
BRANDS = {"oneplus": "Oneplus", "oppo": "Oppo", "realme": "Realme"}

ENTRY = re.compile(
    r'"(?P<pid>[0-9A-F]{6})": DeviceModel\(name: "(?P<name>[^"\\]*)", brand: \.(?P<brand>\w+),\s*'
    r"modeTypes: \[(?P<modes>[^\]]*)\],\s*"
    r"setBits: (?P<setbits>\[[^\]]*\]),\s*"
    r"reportedBits: (?P<repbits>\[[^\]]*\]),\s*"
    r"eqPresets: \[(?P<eq>[^\]]*)\],\s*"
    r"features: (?P<features>nil|\[[^\]]*\])\),",
)


def int_list(text):
    return [int(x) for x in re.findall(r"\d+", text)]


def bit_map(text):
    """`[0: 5, 1: 1]` or `[:]` -> [(0, 5), (1, 1)] sorted by bit."""
    pairs = [(int(a), int(b)) for a, b in re.findall(r"(\d+):\s*(\d+)", text)]
    return sorted(pairs)


def rust_pairs(pairs):
    return "&[" + ", ".join(f"({a}, {b})" for a, b in pairs) + "]"


models = {}
for m in ENTRY.finditer(src):
    pid = m["pid"]
    if pid in models:
        sys.exit(f"duplicate product id {pid}")
    if m["brand"] not in BRANDS:
        sys.exit(f"{pid}: unknown brand {m['brand']}")
    if m["features"] == "nil":
        features = None
    else:
        names = re.findall(r"\.(\w+)", m["features"])
        for n in names:
            if n not in FEATURES:
                sys.exit(f"{pid}: unknown feature {n}")
        features = names
    eq = [(int(a), int(b)) for a, b in re.findall(r"\((\d+),\s*(\d+)\)", m["eq"])]
    models[pid] = dict(
        name=m["name"],
        brand=BRANDS[m["brand"]],
        modes=int_list(m["modes"]),
        setbits=bit_map(m["setbits"]),
        repbits=bit_map(m["repbits"]),
        eq=eq,
        features=features,
    )

expected = len(re.findall(r'^\s+"[0-9A-F]{6}": DeviceModel\(', src, re.M))
if len(models) != expected:
    sys.exit(f"parsed {len(models)} entries but the file has {expected}")

out = []
out.append(
    """// Generated by tools/convert_catalog.py from the upstream Sources/DeviceCatalog.swift. Do not edit by hand.
//
// Model data derived from:
// - RawS-Music's HeyMelody device profiles (Apache License 2.0), https://github.com/QFDY-GZC/RawS-Music
// - the Noctalia oppo-pods plugin (MIT, Copyright (c) 2026 osp54),
//   https://github.com/noctalia-dev/community-plugins/tree/main/oppo-pods
// See THIRD_PARTY_NOTICES.md.

use super::DeviceModel;
use crate::types::{Brand, DeviceFeature};

/// Sorted by product ID (binary-searched by `catalog::lookup`).
pub static MODELS: &[(&str, DeviceModel)] = &["""
)
for pid in sorted(models):
    d = models[pid]
    if d["features"] is None:
        feats = "None"
    else:
        feats = "Some(&[" + ", ".join(f"DeviceFeature::{FEATURES[f]}" for f in d["features"]) + "])"
    modes = "&[" + ", ".join(str(x) for x in d["modes"]) + "]"
    out.append(f'    ("{pid}", DeviceModel {{')
    out.append(f'        name: "{d["name"]}",')
    out.append(f"        brand: Brand::{d['brand']},")
    out.append(f"        mode_types: {modes},")
    out.append(f"        set_bits: {rust_pairs(d['setbits'])},")
    out.append(f"        reported_bits: {rust_pairs(d['repbits'])},")
    out.append(f"        eq_presets: {rust_pairs(d['eq'])},")
    out.append(f"        features: {feats},")
    out.append("    }),")
out.append("];")
sys.stdout.write("\n".join(out) + "\n")
print(f"// {len(models)} models", file=sys.stderr)
